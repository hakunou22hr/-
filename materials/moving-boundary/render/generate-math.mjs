import {createRequire} from 'node:module';import {mkdir,writeFile,readFile} from 'node:fs/promises';import {equations} from '../math-source.js';
const require=createRequire(import.meta.url),{chromium}=require('playwright'),katex=require('katex');
const root=new URL('../math/',import.meta.url);await mkdir(root,{recursive:true});
const browser=await chromium.launch({executablePath:'/usr/bin/chromium',args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:3600,height:600},deviceScaleFactor:3});
await page.route('**/math-render',route=>route.fulfill({contentType:'text/html',body:'<!doctype html><html><body></body></html>'}));
await page.goto('http://127.0.0.1:4173/math-render');
await page.setContent('<style>body{margin:0;background:transparent}#math{display:inline-block;padding:8px;color:white;font-size:64px}.katex{font-size:1em}</style><span id="math"></span>');
let css=await readFile('node_modules/katex/dist/katex.min.css','utf8');
css=css.replace(/url\((fonts\/[^)]+)\)/g,(_,p)=>`url(http://127.0.0.1:4173/node_modules/katex/dist/${p})`);
await page.addStyleTag({content:css+'\n.katex{font-size:1em}'});
const entries=[];let n=0;
for(const [label,tex] of Object.entries(equations)){
 const html=katex.renderToString(tex,{displayMode:true,throwOnError:true,output:'html',strict:'error'});
 await page.locator('#math').evaluate((el,html)=>el.innerHTML=html,html);await page.evaluate(()=>document.fonts.ready);
 await page.addStyleTag({content:'.katex-display{margin:0}'});
 const box=await page.locator('#math').boundingBox(),id=`m${String(n++).padStart(2,'0')}`;
 await page.locator('#math').screenshot({path:new URL(id+'.png',root).pathname,omitBackground:true});
 entries.push(`${JSON.stringify(label)}:{url:new URL('./math/${id}.png',import.meta.url).href,width:${box.width/64},height:${box.height/64}}`);
}
await writeFile(new URL('../math-assets.js',import.meta.url),'// Generated by render/generate-math.mjs from KaTeX; no remote runtime dependency.\nexport const assets={\n'+entries.join(',\n')+'\n};\n');
await browser.close();console.log('KaTeX assets:',n);
